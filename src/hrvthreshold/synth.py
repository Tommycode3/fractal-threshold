"""Synthetic signals with known DFA exponent, for validation.

Power-law noise with spectrum S(f) ~ 1/f^beta has DFA exponent
alpha = (beta + 1) / 2 for -1 < beta < 3:
white (beta=0) -> 0.5, pink (beta=1) -> 1.0, Brownian (beta=2) -> 1.5.
Generated by spectral synthesis (random phases, power-law amplitudes);
Brownian motion is also available as the exact cumulative sum of white noise.
"""

from __future__ import annotations

import numpy as np


def power_law_noise(n: int, beta: float, rng: np.random.Generator | None = None) -> np.ndarray:
    rng = np.random.default_rng() if rng is None else rng
    f = np.fft.rfftfreq(n)
    amp = np.zeros_like(f)
    amp[1:] = f[1:] ** (-beta / 2.0)
    spec = amp * (rng.standard_normal(f.size) + 1j * rng.standard_normal(f.size))
    x = np.fft.irfft(spec, n)
    return (x - x.mean()) / x.std()


def noise_with_alpha(n: int, alpha: float, rng: np.random.Generator | None = None) -> np.ndarray:
    return power_law_noise(n, 2.0 * alpha - 1.0, rng)


def white_noise(n, rng=None):
    rng = np.random.default_rng() if rng is None else rng
    return rng.standard_normal(n)


def brownian_noise(n, rng=None):
    return np.cumsum(white_noise(n, rng))


def synthetic_ramp(
    duration_s: float = 1500.0,
    hr_start: float = 95.0,
    hr_end: float = 185.0,
    alpha_start: float = 1.1,
    alpha_end: float = 0.3,
    sd_start_ms: float = 25.0,
    sd_end_ms: float = 3.0,
    seg_beats: int = 64,
    seed: int = 0,
):
    """RR series of an idealised incremental test (SYNTHETIC, for demos/tests).

    HR rises linearly; the fractal exponent of the beat-to-beat fluctuation
    falls linearly from ``alpha_start`` to ``alpha_end``; amplitude shrinks.
    Built from short segments of power-law noise with the local target alpha.
    Returns (rr_ms, alpha_true_per_beat, hr_true_per_beat).
    """
    rng = np.random.default_rng(seed)
    rr, a_true, hr_true = [], [], []
    t = 0.0
    while t < duration_s:
        u = t / duration_s
        hr = hr_start + u * (hr_end - hr_start)
        a = alpha_start + u * (alpha_end - alpha_start)
        sd = sd_start_ms + u * (sd_end_ms - sd_start_ms)
        # draw a long realisation and keep its centre to limit edge effects
        seg = noise_with_alpha(seg_beats * 4, a, rng)[seg_beats : 2 * seg_beats]
        seg = 60000.0 / hr + sd * (seg - seg.mean()) / seg.std()
        rr.extend(seg)
        a_true.extend([a] * seg_beats)
        hr_true.extend([hr] * seg_beats)
        t += seg.sum() / 1000.0
    return np.array(rr), np.array(a_true), np.array(hr_true)
